-- Customer menu in the database. Run after 011. Safe to re-run (seeds only when empty).
create table if not exists public.menu_categories (
  id text primary key check (id ~ '^[a-z0-9_-]{1,40}$'),
  name_ar text not null, name_en text not null default '',
  sort int not null default 0, hidden boolean not null default false
);
create table if not exists public.menu_items (
  id bigint generated always as identity primary key,
  category_id text not null references public.menu_categories(id) on update cascade on delete cascade,
  kind text not null default 'item' check (kind in ('item','sub','extra')),
  name text not null check (length(name) between 1 and 120),
  descr text not null default '',
  prices int[] not null default '{}' check (cardinality(prices) <= 4),
  image_url text not null default '',
  sort int not null default 0,
  hidden boolean not null default false,
  out_of_stock boolean not null default false,
  highlight boolean not null default false,
  updated_at timestamptz not null default now()
);
create index if not exists menu_items_cat on public.menu_items(category_id, sort);
alter table public.menu_categories enable row level security;
alter table public.menu_items enable row level security;
drop policy if exists "menu cat read" on public.menu_categories;
drop policy if exists "menu cat admin" on public.menu_categories;
drop policy if exists "menu item read" on public.menu_items;
drop policy if exists "menu item admin" on public.menu_items;
create policy "menu cat read" on public.menu_categories for select to anon, authenticated using (true);
create policy "menu cat admin" on public.menu_categories for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "menu item read" on public.menu_items for select to anon, authenticated using (true);
create policy "menu item admin" on public.menu_items for all to authenticated using (public.is_admin()) with check (public.is_admin());
grant select on public.menu_categories, public.menu_items to anon, authenticated;
grant insert, update, delete on public.menu_categories, public.menu_items to authenticated;

