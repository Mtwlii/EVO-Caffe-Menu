#!/usr/bin/env node
// Usage: node scripts/new-client.js --admin owner@cafe.com [--out db/all.sql]
// Builds ONE sql file (001..latest) for a fresh Supabase project, with the admin email swapped in.
// Paste the output in the Supabase SQL editor (run once). Nothing is sent anywhere.
var fs = require('fs'), path = require('path');
var a = process.argv.slice(2), opt = {};
for (var i = 0; i < a.length; i += 2) opt[a[i].replace(/^--/, '')] = a[i + 1];
if (!opt.admin || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(opt.admin)) { console.error('need --admin email'); process.exit(1); }
var dir = path.join(__dirname, '..', 'db');
var files = fs.readdirSync(dir).filter(function (f) { return /^\d{3}_.*\.sql$/.test(f); }).sort();
var out = '-- Generated by scripts/new-client.js for ' + opt.admin + '. Files: ' + files.join(', ') + '\n';
files.forEach(function (f) {
  var s = fs.readFileSync(path.join(dir, f), 'utf8').split('metwlii.dev@gmail.com').join(opt.admin.toLowerCase());
  out += '\n-- ===== ' + f + ' =====\n' + s + '\n';
});
var dest = opt.out || path.join(dir, 'all.sql');
fs.writeFileSync(dest, out);
console.log('wrote ' + dest + ' (' + files.length + ' migrations). Next: docs/ONBOARDING.md step 3.');
